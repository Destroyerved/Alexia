"""Sandbox test execution environment with red-to-green proof of fix verification.

Implements FR-B3, FR-B4, FR-D4:
- Copies the target app into a throwaway directory (optionally with the deployed commit applied).
- Runs the generated regression test before the patch: it must FAIL (RED) to prove the bug.
- Applies the generated unified diff (pure-Python, see diffutil) and reruns the test: it must PASS (GREEN).
- Results are reported exactly as they happened; nothing is marked green that did not pass.
- `smoke_test` probes key endpoints of a candidate deploy for the Deployer's health gate.

Tests run in a separate process (pytest when available, else alexia.tools.mini_pytest, which the
frozen AlexiaServer.exe exposes as `--sandbox-test`), with a 120 s timeout.
"""

from __future__ import annotations
import logging
import os
import shutil
import subprocess
import sys
import tempfile
from typing import Any, Dict, List, Optional, Tuple

from alexia.tools.diffutil import apply_diff_to_dir

logger = logging.getLogger("alexia.sandbox")

TEST_TIMEOUT_SECONDS = 120
_SKIP = {"__pycache__", ".pytest_cache"}

SMOKE_TEST = '''"""Post-deploy smoke probe generated by Alexia's Deployer health gate."""
from fastapi.testclient import TestClient
from app.main import app

client = TestClient(app)  # server-side exceptions propagate, so the gate reports the real error


def probe(path, **params):
    try:
        resp = client.get(path, params=params)
    except Exception as exc:
        raise AssertionError(f"HTTP 500 {type(exc).__name__} on {path} {params}: {exc}") from None
    assert resp.status_code < 500, f"HTTP {resp.status_code} on {path} {params}"
    return resp


def test_health_endpoint():
    assert probe("/health").status_code == 200


def test_search_endpoint():
    probe("/search", q="Keyboard")


def test_order_total_endpoint():
    for count in (2, 1, 0):
        probe("/orders/total", subtotal=100.0, item_count=count)
'''


def default_workspace() -> str:
    """target-app next to the working directory, else the copy bundled inside AlexiaServer.exe."""
    local = os.path.abspath("target-app")
    if os.path.isdir(local):
        return local
    return os.path.join(getattr(sys, "_MEIPASS", os.getcwd()), "target-app")


def _test_command(test_file_rel: str) -> List[str]:
    if getattr(sys, "frozen", False):
        return [sys.executable, "--sandbox-test", test_file_rel]
    try:
        import pytest  # noqa: F401

        return [sys.executable, "-m", "pytest", test_file_rel, "-q", "-p", "no:cacheprovider", "--tb=short"]
    except ImportError:
        return [sys.executable, "-m", "alexia.tools.mini_pytest", test_file_rel]


class SandboxRunner:
    """Executes sandboxed tests with before/after regression verification."""

    def __init__(self, workspace_path: Optional[str] = None):
        self.workspace_path = workspace_path or default_workspace()

    def run_command(self, cmd: List[str], cwd: str, timeout: int = 60) -> Tuple[int, str, str]:
        """Execute a command in the sandbox directory with the sandbox on PYTHONPATH."""
        env = dict(os.environ)
        repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
        env["PYTHONPATH"] = os.pathsep.join([cwd, repo_root])
        env["DATABASE_URL"] = "sqlite:///data/shoplite.db"
        env.setdefault("DEMO_VULN", "1")
        env["PYTHONIOENCODING"] = "utf-8"
        try:
            res = subprocess.run(
                cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout, env=env,
                encoding="utf-8", errors="replace",
            )
            return res.returncode, res.stdout, res.stderr
        except subprocess.TimeoutExpired:
            return 124, "", f"Execution timed out after {timeout} seconds"
        except Exception as e:
            return 1, "", str(e)

    def _prepare(self) -> str:
        temp_dir = tempfile.mkdtemp(prefix="alexia_sandbox_")
        if os.path.isdir(self.workspace_path):
            shutil.copytree(
                self.workspace_path, temp_dir, dirs_exist_ok=True,
                ignore=lambda _d, names: [n for n in names if n in _SKIP or n.endswith(".pyc")],
            )
        os.makedirs(os.path.join(temp_dir, "tests"), exist_ok=True)
        os.makedirs(os.path.join(temp_dir, "data"), exist_ok=True)
        return temp_dir

    def _run_test(self, temp_dir: str, test_file_rel: str) -> Tuple[int, str]:
        code, out, err = self.run_command(_test_command(test_file_rel), cwd=temp_dir, timeout=TEST_TIMEOUT_SECONDS)
        return code, f"{out}\n{err}".strip()

    def read_workspace_file(self, rel_path: str, base_diff: str = "") -> str:
        """Source of a target file as deployed (base_diff applied), for the Builder's prompt."""
        temp_dir = self._prepare()
        try:
            if base_diff:
                apply_diff_to_dir(temp_dir, base_diff)
            path = os.path.join(temp_dir, rel_path)
            if not os.path.exists(path):
                return ""
            with open(path, encoding="utf-8") as f:
                return f.read()
        finally:
            shutil.rmtree(temp_dir, ignore_errors=True)

    def verify_patch(
        self,
        failing_test_code: str,
        patch_diff: str,
        base_diff: str = "",
        test_file_rel: str = "tests/test_regression.py",
    ) -> Dict[str, Any]:
        """Run the Red -> Green cycle and report what actually happened."""
        temp_dir = self._prepare()
        try:
            base_note = ""
            if base_diff:
                ok, msg, _ = apply_diff_to_dir(temp_dir, base_diff)
                base_note = f"Deployed commit applied: {msg}" if ok else f"Deployed commit did not apply: {msg}"

            full_test_path = os.path.join(temp_dir, test_file_rel)
            os.makedirs(os.path.dirname(full_test_path), exist_ok=True)
            with open(full_test_path, "w", encoding="utf-8") as tf:
                tf.write(failing_test_code)

            # Phase 1: RED - the regression test must fail against the buggy code
            code_before, before_log = self._run_test(temp_dir, test_file_rel)
            failed_before = code_before != 0

            # Phase 2: apply the generated patch
            patch_applied, patch_message, _ = apply_diff_to_dir(temp_dir, patch_diff)

            # Phase 3: GREEN - the same test must pass against the patched code
            if patch_applied:
                code_after, after_log = self._run_test(temp_dir, test_file_rel)
                passed_after = code_after == 0
            else:
                passed_after = False
                after_log = f"Patch did not apply: {patch_message}"

            success = failed_before and patch_applied and passed_after
            if success:
                summary = "Fix verified: test FAILED before the patch (RED) and PASSED after it (GREEN)."
            elif not failed_before:
                summary = "Not proven: the regression test already passed before the patch, so it does not reproduce the bug."
            elif not patch_applied:
                summary = f"Not proven: the patch did not apply ({patch_message})."
            else:
                summary = "Not proven: the regression test still fails after the patch."
            return {
                "success": success,
                "failed_before": failed_before,
                "passed_after": passed_after,
                "patch_applied": patch_applied,
                "patch_message": patch_message,
                "base_note": base_note,
                "before_log": before_log,
                "after_log": after_log,
                "failing_test_code": failing_test_code,
                "patch_diff": patch_diff,
                "test_runner": "pytest" if "pytest" in _test_command(test_file_rel) else "alexia mini-runner",
                "summary": summary,
            }
        finally:
            shutil.rmtree(temp_dir, ignore_errors=True)

    def smoke_test(self, deploy_diff: str = "") -> Tuple[bool, str]:
        """Health-gate probe: apply the candidate deploy to a copy of the app and hit key endpoints."""
        temp_dir = self._prepare()
        try:
            if deploy_diff:
                apply_diff_to_dir(temp_dir, deploy_diff)
            test_rel = "tests/test_alexia_smoke.py"
            with open(os.path.join(temp_dir, test_rel), "w", encoding="utf-8") as f:
                f.write(SMOKE_TEST)
            code, log = self._run_test(temp_dir, test_rel)
            return code == 0, log
        finally:
            shutil.rmtree(temp_dir, ignore_errors=True)


_global_sandbox: Optional[SandboxRunner] = None


def get_sandbox_runner() -> SandboxRunner:
    """Retrieve or initialize SandboxRunner."""
    global _global_sandbox
    if _global_sandbox is None:
        _global_sandbox = SandboxRunner()
    return _global_sandbox
