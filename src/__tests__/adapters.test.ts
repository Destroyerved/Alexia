import { describe, expect, it } from 'vitest';
import { toDeploymentRecord, toSecurityReport, toSnapshotRecord } from '../lib/adapters';

describe('backend -> view-model adapters', () => {
  it('maps a backend deployment, keeping rollback eligibility', () => {
    const dep = toDeploymentRecord({
      id: 'dep_141_good',
      service_name: 'shoplite-api',
      version: 'v1.4.1',
      previous_version: 'v1.4.0',
      status: 'healthy',
      pre_deploy_Review: 'passed',
      health_gate: 'passed',
      rollback_available: true,
      timestamp: '2026-10-28T09:15:00Z',
    });
    expect(dep.image_tag).toBe('shoplite-api:v1.4.1');
    expect(dep.previous_known_good_image).toBe('shoplite-api:v1.4.0');
    expect(dep.status).toBe('Successful');
    expect(dep.rollback_available).toBe(true);
    expect([...dep.pre_deploy_gates, ...dep.health_gates].every((g) => g.passed)).toBe(true);
  });

  it('maps a snapshot and converts size to bytes', () => {
    const snap = toSnapshotRecord({ id: 'snap_1', size_mb: 1, sha256: 'ab'.repeat(32), verified: true, restorable: true, type: 'full_bundle' });
    expect(snap.size_bytes).toBe(1024 * 1024);
    expect(snap.integrity_status).toBe('valid');
    expect(snap.sha256_checksum).toHaveLength(64);
  });

  it('splits a Sentinel markdown draft into sections and always carries the DRAFT disclaimer', () => {
    const rep = toSecurityReport({
      id: 'rep_cert_in_inc_1',
      incident_id: 'inc_1',
      framework: 'CERT-In',
      framework_label: 'CERT-In 6-Hour Cyber Incident Directive (India)',
      markdown: '# CERT-In Report\n\nIntro\n\n## Indicators\n- 198.51.100.88\n\n## Actions Taken\nIP blocked',
    });
    expect(rep.report_type).toBe('cert_in');
    expect(rep.sections.map((s) => s.heading)).toEqual(['CERT-In Report', 'Indicators', 'Actions Taken']);
    expect(rep.disclaimer).toMatch(/^DRAFT generated by Alexia\. Not legal advice\./);
  });

  it('builds sections for seeded report records without markdown', () => {
    const rep = toSecurityReport({ id: 'rep_gdpr_s6', framework: 'GDPR', summary: 'x', root_cause: 'CWE-89', data_categories_exposed: ['email'] });
    expect(rep.report_type).toBe('gdpr_draft');
    expect(rep.sections.find((s) => s.heading === 'Root cause')?.content).toBe('CWE-89');
  });
});
